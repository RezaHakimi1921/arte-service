export type PlateParts = { two: string; letter: string; three: string; region: string };

/** Motorcycle plate: 3 digits on top, 5 below → "123-45678". */
export type MotoPlateParts = { top: string; bottom: string };

export function parseMotoPlate(identifier: string | null | undefined): MotoPlateParts | null {
  const m = identifier?.match(/^(\d{3})-(\d{5})$/);
  return m ? { top: m[1], bottom: m[2] } : null;
}

export function formatMotoPlate(p: MotoPlateParts): string | null {
  return p.top.length === 3 && p.bottom.length === 5 ? `${p.top}-${p.bottom}` : null;
}

/** "12ب345-11" ⇄ parts. Anything else is treated as a free-text identifier. */
export function parsePlate(identifier: string | null | undefined): PlateParts | null {
  const m = identifier?.match(/^(\d{2})(\D{1,3})(\d{3})-(\d{2})$/);
  return m ? { two: m[1], letter: m[2], three: m[3], region: m[4] } : null;
}

export function formatPlate(p: PlateParts): string | null {
  return p.two.length === 2 && p.letter && p.three.length === 3 && p.region.length === 2 ? `${p.two}${p.letter}${p.three}-${p.region}` : null;
}

export function currentJalaliYear(): number {
  const y = new Intl.DateTimeFormat("en-US-u-ca-persian", { year: "numeric" }).format(new Date());
  return parseInt(y, 10);
}

/** Years to offer for a model: its production range when known, otherwise the last 45 years. Newest first. */
export function modelYears(entry: ModelEntry | undefined, calendar: "jalali" | "gregorian", all: boolean): number[] {
  const nowJ = currentJalaliYear();
  let from = nowJ - 45;
  let to = nowJ + 1;
  if (!all && entry?.[1]) {
    from = entry[1];
    to = entry[2] ?? nowJ + 1;
  }
  const shift = calendar === "gregorian" ? 621 : 0;
  const years: number[] = [];
  for (let y = to; y >= from; y--) years.push(y + shift);
  return years;
}
